'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const app=fs.readFileSync('app.js','utf8');
const html=fs.readFileSync('index.html','utf8');
const bank=JSON.parse(fs.readFileSync('questions.json','utf8'));
const groups=JSON.parse(fs.readFileSync('chapter-groups.json','utf8'));
assert.equal(bank.length,500);
assert.equal(groups.chapters.length,14);
assert.equal(groups.groups.length,22);
assert.ok(app.includes('document.body.classList.toggle(\'quiz-active\',quizScreen)'), 'quiz class should track active screen');
assert.ok(app.includes("'<div class=\"actions\">'+button('pause','暫存並回首頁',true)+'</div>',true);"), 'question renderer must enable compact mode');
assert.ok(html.includes('body.quiz-active > header{display:none!important}'),'site banner should hide in mobile quiz');
assert.ok(html.includes('body.quiz-active #app .question{font-size:1.2rem'),'question typography should be enlarged on mobile');
assert.ok(html.includes('body.quiz-active .option:not(.selected):hover'),'touch hover residue should be neutralized');
assert.ok(app.includes('el.blur?.();'),'tapped button focus should clear');
assert.ok(app.includes('const chapterOneNotice=source===\'trade\''),'missing optional first chapter');
assert.ok(app.includes('一、經貿資訊'),'missing first chapter heading');
assert.ok(!groups.chapters.some(c=>c.id==='T01'),'no invented first-chapter questions');
assert.ok(html.includes('lc-case1-refs1'),'updated JS cache-bust missing');
console.log('PASS: mobile quiz header hidden, answer options reset and trade chapter one described without questions.');
