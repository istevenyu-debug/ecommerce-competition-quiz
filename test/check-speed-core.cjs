'use strict';
const assert = require('node:assert/strict');
const C = require('../speed-core.js');
const bank = require('../questions.json');
assert.deepEqual([...C.LIMITS], [20, 15, 10, 5, 3]);
assert.equal(C.STORAGE_KEY, 'ecommerce-speed-training-v1');
assert.notEqual(C.STORAGE_KEY, 'ecommerce-quiz-local-v1');
assert.equal(C.validateBank(bank), true);
const seen = {}, unique = new Set();
for (let round = 0; round < 100; round++) {
  const paper = C.selectPaper(bank, seen);
  assert.equal(paper.length, 30);
  assert.equal(new Set(paper.map(q => q.id)).size, 30);
  assert.equal(paper.filter(q => q.source === 'trade').length, 25);
  assert.equal(paper.filter(q => q.source === 'ecom').length, 5);
  assert.ok(paper.every(q => !q.contextRequired && !q.caseId && q.chapterId !== 'T12'));
  paper.forEach(q => { seen[q.id] = (seen[q.id] || 0) + 1; unique.add(q.id); });
  if (round === 19) assert.equal(unique.size, 450, '20 rounds must cover all eligible questions');
}
const q = bank[0];
for (const limit of C.LIMITS) {
  const max = limit * 1000;
  const clock = new C.QuestionClock(q, limit, 10000);
  assert.equal(clock.remaining(10000), max);
  const answer = clock.settle(q.answer, 10000 + max / 4);
  assert.equal(answer.status, 'correct');
  assert.equal(answer.elapsedMs, max / 4);
  assert.equal(answer.pointsTenths, 925);
  assert.equal(clock.settle((q.answer + 1) % 4, 10000 + max / 2), null, 'answer must lock');
  assert.equal(C.scoreAnswer(q, q.answer, max, limit).status, 'timeout', 'deadline equality is too late');
  assert.equal(C.scoreAnswer(q, q.answer, max - 1, limit).status, 'correct');
  assert.equal(C.scoreAnswer(q, q.answer, max + 50, limit).choice, null);
  assert.equal(C.scoreAnswer(q, null, max + 50, limit).elapsedMs, max);
  assert.equal(C.scoreAnswer(q, (q.answer + 1) % 4, 0, limit).pointsTenths, 0);
  assert.equal(C.scoreAnswer(q, q.answer, 0, limit).pointsTenths, 1000);
  assert.ok(C.scoreAnswer(q, q.answer, max / 4, limit).pointsTenths > C.scoreAnswer(q, q.answer, max / 2, limit).pointsTenths);
}
assert.throws(() => C.scoreAnswer(q, 4, 0, 15));
assert.throws(() => C.scoreAnswer(q, 0, Infinity, 15));
assert.throws(() => C.scoreAnswer(q, 0, 1000, 7));
const results = C.selectPaper(bank).map(q => C.scoreAnswer(q, q.answer, 500, 15));
results[3] = C.scoreAnswer(bank[0], null, 15000, 15);
results[9] = C.scoreAnswer(bank[1], null, 15000, 15);
const sum = C.summarize(results);
assert.equal(sum.total, 30); assert.equal(sum.correct, 28); assert.equal(sum.timeouts, 2);
assert.equal(sum.score, 93); assert.equal(sum.slowestIndex, 3, 'ties use first slowest');
assert.equal(sum.totalMs, 44000);
assert.equal(sum.pointsTenths, results.reduce((n, r) => n + r.pointsTenths, 0));
assert.equal(C.formatTime(0), '00:00.0'); assert.equal(C.formatTime(89999), '01:30.0');
assert.deepEqual(C.loadState('{bad'), C.emptyState());
assert.deepEqual(C.loadState(null), C.emptyState());
assert.equal(C.loadState('{"selectedSeconds":7}').selectedSeconds, 15);
let state = C.emptyState();
for (let i = 0; i < 13; i++) state = C.addCompleted(state, { id: String(i), time: i, limitSeconds: 15, results, summary: sum });
assert.equal(state.history.length, 10); assert.equal(state.history[0].id, '12'); assert.equal(state.history[9].id, '3');
const counts = JSON.stringify(state.seen);
state = C.addCompleted(state, state.history[0]);
assert.equal(JSON.stringify(state.seen), counts, 'same result must not increment twice');
assert.throws(() => C.addCompleted(state, { id: 'bad', results: results.slice(0, 29) }));
assert.equal(C.loadState(JSON.stringify(state)).history.length, 10);
console.log('PASS: 25+5 unique selection / 450-question coverage / five limits / timing boundaries / locked answers / weighted score / slowest tie / isolated last 10 results.');
